-- Matches data_warehouse_model.drawio (snake_case SQL names).
-- Run once in the existing glovo database, after 01..05.
-- dw is a schema inside glovo; public contains the operational tables.
-- This file creates the warehouse structure; 07 will load the source data.
-- Currency: EUR. Calendar timezone: Europe/Sofia.

BEGIN;

CREATE SCHEMA dw;

-- =========================================================
-- 1. SEVEN SHARED DIMENSIONS
-- Type 1: update current attributes; no historical versions.
-- Source IDs identify operational records, not warehouse PKs.
-- =========================================================

CREATE TABLE dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year SMALLINT NOT NULL,
    quarter SMALLINT NOT NULL,
    month SMALLINT NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    day_of_month SMALLINT NOT NULL,
    day_of_week_iso SMALLINT NOT NULL,
    is_weekend BOOLEAN NOT NULL,

    CONSTRAINT ck_dim_date_year CHECK (year BETWEEN 1 AND 9999),
    CONSTRAINT ck_dim_date_parts CHECK (
        year = EXTRACT(YEAR FROM full_date)
        AND quarter = EXTRACT(QUARTER FROM full_date)
        AND month = EXTRACT(MONTH FROM full_date)
        AND day_of_month = EXTRACT(DAY FROM full_date)
        AND day_of_week_iso = EXTRACT(ISODOW FROM full_date)
        AND is_weekend = (day_of_week_iso IN (6, 7))
        AND date_key = year::INTEGER * 10000
                       + month::INTEGER * 100 + day_of_month
    )
);

CREATE TABLE dw.dim_customer (
    customer_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    registered_at TIMESTAMPTZ NOT NULL,
    is_active BOOLEAN NOT NULL
);

CREATE TABLE dw.dim_restaurant (
    restaurant_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    street_address TEXT NOT NULL,
    is_active BOOLEAN NOT NULL
);

CREATE TABLE dw.dim_location (
    location_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    address_id BIGINT NOT NULL UNIQUE,
    city VARCHAR(100) NOT NULL,
    district VARCHAR(100),
    postal_code VARCHAR(20)
);

CREATE TABLE dw.dim_product (
    product_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    category_name VARCHAR(100) NOT NULL,
    is_available BOOLEAN NOT NULL
);

CREATE TABLE dw.dim_payment_method (
    payment_method_key INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_method_id BIGINT NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    is_active BOOLEAN NOT NULL
);

CREATE TABLE dw.dim_courier (
    -- BY DEFAULT permits the reserved warehouse key 0.
    courier_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id BIGINT UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    vehicle_type VARCHAR(30) NOT NULL,

    CONSTRAINT ck_courier_unknown_member CHECK (
        (courier_key = 0 AND courier_id IS NULL)
        OR (courier_key > 0 AND courier_id IS NOT NULL)
    )
);

INSERT INTO dw.dim_courier (
    courier_key, courier_id, first_name, last_name, vehicle_type
)
VALUES (0, NULL, 'Unknown', 'Unassigned', 'unknown');

-- =========================================================
-- 2. FACT: ORDER ITEMS
-- Grain: one row per (source order, warehouse product).
-- Load cancelled orders too; filter delivered for completed sales.
-- Delivery fees are intentionally absent at this grain.
-- =========================================================

CREATE TABLE dw.fact_order_items (
    order_item_fact_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key INTEGER NOT NULL REFERENCES dw.dim_customer(customer_key),
    restaurant_key INTEGER NOT NULL
        REFERENCES dw.dim_restaurant(restaurant_key),
    location_key INTEGER NOT NULL REFERENCES dw.dim_location(location_key),
    product_key INTEGER NOT NULL REFERENCES dw.dim_product(product_key),
    order_status VARCHAR(30) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12,2) NOT NULL,
    item_amount NUMERIC(18,2)
        GENERATED ALWAYS AS (quantity::NUMERIC * unit_price) STORED NOT NULL,

    CONSTRAINT uq_fact_order_product UNIQUE (order_id, product_key),
    CONSTRAINT ck_fact_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_fact_item_price CHECK (
        unit_price >= 0 AND unit_price <> 'NaN'::NUMERIC
    ),
    CONSTRAINT ck_fact_item_order_status CHECK (
        order_status IN (
            'pending', 'confirmed', 'preparing', 'ready',
            'delivering', 'delivered', 'cancelled'
        )
    )
);

-- =========================================================
-- 3. FACT: PAYMENTS
-- Grain: one row per source payment (including failed attempts).
-- successful_amount, not amount, measures collected money.
-- order_date_key groups by ORDER date; paid_at is actual payment time.
-- =========================================================

CREATE TABLE dw.fact_payments (
    payment_fact_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE,
    order_id BIGINT NOT NULL,
    order_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key INTEGER NOT NULL REFERENCES dw.dim_customer(customer_key),
    restaurant_key INTEGER NOT NULL
        REFERENCES dw.dim_restaurant(restaurant_key),
    location_key INTEGER NOT NULL REFERENCES dw.dim_location(location_key),
    payment_method_key INTEGER NOT NULL
        REFERENCES dw.dim_payment_method(payment_method_key),
    payment_status VARCHAR(30) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    successful_amount NUMERIC(12,2) GENERATED ALWAYS AS (
        CASE WHEN payment_status = 'successful' THEN amount ELSE 0 END
    ) STORED NOT NULL,
    paid_at TIMESTAMPTZ,

    CONSTRAINT ck_fact_payment_amount CHECK (
        amount > 0 AND amount <> 'NaN'::NUMERIC
    ),
    CONSTRAINT ck_fact_payment_status CHECK (
        payment_status IN ('pending', 'successful', 'failed')
    ),
    CONSTRAINT ck_fact_payment_time CHECK (
        (payment_status = 'successful' AND paid_at IS NOT NULL)
        OR (payment_status IN ('pending', 'failed') AND paid_at IS NULL)
    )
);

-- =========================================================
-- 4. FACT: DELIVERIES
-- Grain: one row per delivery; source order_id is also unique.
-- Accumulating snapshot: refresh status and event times on loading.
-- A missing courier uses dimension member 0 instead of a NULL FK.
-- delivery_minutes measures ORDER creation -> completed delivery.
-- =========================================================

CREATE TABLE dw.fact_deliveries (
    delivery_fact_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL UNIQUE,
    order_id BIGINT NOT NULL UNIQUE,
    order_date_key INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    customer_key INTEGER NOT NULL REFERENCES dw.dim_customer(customer_key),
    restaurant_key INTEGER NOT NULL
        REFERENCES dw.dim_restaurant(restaurant_key),
    location_key INTEGER NOT NULL REFERENCES dw.dim_location(location_key),
    courier_key INTEGER NOT NULL DEFAULT 0 REFERENCES dw.dim_courier(courier_key),
    delivery_status VARCHAR(30) NOT NULL,
    ordered_at TIMESTAMPTZ NOT NULL,
    assigned_at TIMESTAMPTZ,
    picked_up_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    estimated_minutes INTEGER,
    delivery_minutes NUMERIC(10,2) GENERATED ALWAYS AS (
        CASE WHEN delivery_status = 'delivered'
            THEN EXTRACT(EPOCH FROM (delivered_at - ordered_at)) / 60.0
            ELSE NULL
        END
    ) STORED,
    delivery_fee NUMERIC(12,2) NOT NULL,

    CONSTRAINT ck_fact_delivery_status CHECK (
        delivery_status IN (
            'pending', 'assigned', 'picked_up', 'delivered', 'cancelled'
        )
    ),
    CONSTRAINT ck_fact_delivery_fee CHECK (
        delivery_fee >= 0 AND delivery_fee <> 'NaN'::NUMERIC
    ),
    CONSTRAINT ck_fact_delivery_estimate CHECK (estimated_minutes > 0),
    CONSTRAINT ck_fact_delivery_assignment CHECK (
        (courier_key = 0 AND assigned_at IS NULL)
        OR (courier_key > 0 AND assigned_at IS NOT NULL)
    ),
    CONSTRAINT ck_fact_assignment_time CHECK (
        assigned_at IS NULL OR assigned_at >= ordered_at
    ),
    CONSTRAINT ck_fact_pickup_time CHECK (
        picked_up_at IS NULL
        OR (assigned_at IS NOT NULL AND picked_up_at >= assigned_at)
    ),
    CONSTRAINT ck_fact_delivery_time CHECK (
        delivered_at IS NULL
        OR (picked_up_at IS NOT NULL AND delivered_at >= picked_up_at)
    ),
    CONSTRAINT ck_fact_delivery_status_details CHECK (
        (delivery_status = 'pending' AND courier_key = 0
            AND picked_up_at IS NULL AND delivered_at IS NULL)
        OR (delivery_status = 'assigned' AND courier_key > 0
            AND picked_up_at IS NULL AND delivered_at IS NULL)
        OR (delivery_status = 'picked_up' AND courier_key > 0
            AND picked_up_at IS NOT NULL AND delivered_at IS NULL)
        OR (delivery_status = 'delivered' AND courier_key > 0
            AND picked_up_at IS NOT NULL AND delivered_at IS NOT NULL)
        OR (delivery_status = 'cancelled' AND delivered_at IS NULL)
    )
);

-- Common report filters and joins. PK/UQ indexes already exist.
CREATE INDEX ix_dw_items_date ON dw.fact_order_items(order_date_key);
CREATE INDEX ix_dw_items_customer ON dw.fact_order_items(customer_key);
CREATE INDEX ix_dw_items_restaurant ON dw.fact_order_items(restaurant_key);
CREATE INDEX ix_dw_items_location ON dw.fact_order_items(location_key);
CREATE INDEX ix_dw_items_product ON dw.fact_order_items(product_key);

CREATE INDEX ix_dw_payments_order ON dw.fact_payments(order_id);
CREATE INDEX ix_dw_payments_date ON dw.fact_payments(order_date_key);
CREATE INDEX ix_dw_payments_customer ON dw.fact_payments(customer_key);
CREATE INDEX ix_dw_payments_restaurant ON dw.fact_payments(restaurant_key);
CREATE INDEX ix_dw_payments_location ON dw.fact_payments(location_key);
CREATE INDEX ix_dw_payments_method ON dw.fact_payments(payment_method_key);

CREATE INDEX ix_dw_deliveries_date ON dw.fact_deliveries(order_date_key);
CREATE INDEX ix_dw_deliveries_customer ON dw.fact_deliveries(customer_key);
CREATE INDEX ix_dw_deliveries_restaurant ON dw.fact_deliveries(restaurant_key);
CREATE INDEX ix_dw_deliveries_location ON dw.fact_deliveries(location_key);
CREATE INDEX ix_dw_deliveries_courier ON dw.fact_deliveries(courier_key);

COMMENT ON SCHEMA dw IS
    'Glovo analytical warehouse: 7 dimensions and 3 facts; EUR; Europe/Sofia dates.';
COMMENT ON COLUMN dw.fact_order_items.unit_price IS
    'Historical price copied from public.order_items, never current product price.';
COMMENT ON COLUMN dw.fact_order_items.item_amount IS
    'Quantity * historical unit price. Excludes delivery fee. Filter delivered for completed sales.';
COMMENT ON COLUMN dw.fact_payments.successful_amount IS
    'Collected amount, zero for pending/failed attempts. Includes delivery fees.';
COMMENT ON COLUMN dw.fact_deliveries.delivery_minutes IS
    'Minutes from order creation to completed delivery; NULL for non-completed deliveries.';

COMMIT;
